/**
 * Герб команды без логотипа.
 *
 * В примерах ответов самой спеки `logo_url` в основном `null`, поэтому вид
 * «нет логотипа» — основной, а не аварийный. Команда получает монограмму на
 * цветном щите; цвет выводится детерминированно из `team.id`.
 *
 * Дисциплина, без которой приём вредит:
 *
 * 1. Сеем ТОЛЬКО на `id`, никогда на `slug`. Slug генерируется из названия
 *    транслитерацией: админ правит опечатку → slug меняется → команда, которую
 *    болельщики запомнили по цвету, молча перекрашивается.
 *
 * 2. Различает МОНОГРАММА, а не цвет. 9 слотов на десятки команд — коллизии
 *    по принципу Дирихле неизбежны и наступают уже внутри одной таблицы.
 *    Цвет — вторичное украшение.
 *
 * 3. Строки таблицы цветом команды НЕ тонируются: восемь строк восьми оттенков
 *    убивают вертикальное сканирование колонок — ровно то, ради чего таблица
 *    существует, — и роняют контраст приглушённого текста.
 */

/**
 * Светлота и хрома зафиксированы: oklch(0.45 0.115 H). Именно фиксация даёт
 * гарантию — белый текст на любом слоте ≥ 6.69 : 1 (проверено по всем девяти),
 * то есть автоцвет не может провалить WCAG AA.
 *
 * Оттенки курированы: H ∈ {263, 293, 323, 353, 23, 143, 173, 203, 233}.
 * Диапазон 53…113 (горчица, олива) исключён — в хоккейном контексте выглядит грязно.
 */
const CREST_COLORS = [
  '#325294', // H=263 — брендовый синий, 7.58:1
  '#59468E', // H=293 — фиолетовый,      7.80:1
  '#733C7A', // H=323 — пурпурный,       7.91:1
  '#83365B', // H=353 — вишнёвый,        7.94:1
  '#8A3636', // H=23  — кирпичный,       7.89:1
  '#276526', // H=143 — зелёный,         7.06:1
  '#00694F', // H=173 — изумрудный,      6.70:1
  '#006671', // H=203 — бирюзовый,       6.69:1
  '#005E8A', // H=233 — стальной синий,  7.08:1
] as const

export function crestColor(teamId: number): string {
  const i = ((teamId % CREST_COLORS.length) + CREST_COLORS.length) % CREST_COLORS.length
  return CREST_COLORS[i]!
}

/**
 * Монограмма: две буквы. По первым буквам двух слов («Крылья Советов» → «КС»),
 * а для одного слова — первые две буквы («Сокол» → «СО»).
 * Кавычки, дефисы и цифры отбрасываются.
 */
export function crestInitials(name: string | null | undefined): string {
  if (!name) return '—'

  const words = name
    .replace(/[«»"'`()[\]]/g, ' ')
    .split(/[\s\-—/]+/)
    .map(w => w.replace(/[^\p{L}\p{N}]/gu, ''))
    .filter(Boolean)

  if (!words.length) return '—'

  if (words.length === 1) {
    return words[0]!.slice(0, 2).toUpperCase()
  }
  return (words[0]![0]! + words[1]![0]!).toUpperCase()
}

/** Инициалы игрока из ФИО: «Иван Петров» → «ИП» */
export function playerInitials(fullName: string | null | undefined): string {
  if (!fullName) return '—'
  const words = fullName.split(/\s+/).filter(Boolean)
  if (!words.length) return '—'
  if (words.length === 1) return words[0]!.slice(0, 2).toUpperCase()
  return (words[0]![0]! + words[1]![0]!).toUpperCase()
}
